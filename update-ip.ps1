<#
.SYNOPSIS
  Change the remote exit IP in AcrylicHosts.txt and restart the service.
  Optionally re-fetch domains.txt from a URL (e.g. your AdGuard gist) first.

.PARAMETER NewIP
  New exit IP. Required unless -DomainsUrl is given (then per-line IPs are used).

.PARAMETER DomainsUrl
  Optional URL of an AdGuard-style domains list (||domain^$dnsrewrite=IP).
  When set, hosts are regenerated from it instead of just swapping the IP.

.EXAMPLE
  .\update-ip.ps1 -NewIP 1.2.3.4
.EXAMPLE
  .\update-ip.ps1 -RefreshDomains
.EXAMPLE
  .\update-ip.ps1 -DomainsUrl https://gist.githubusercontent.com/.../domains.txt
#>
param(
  [string]$NewIP = '',
  [string]$DomainsUrl = '',
  [switch]$RefreshDomains,
  [string]$InstallDir = "$env:LOCALAPPDATA\AcrylicDNS",
  [string]$RepoBase = 'https://raw.githubusercontent.com/fdoo24/acrylic-dns-unlock/main',
  [string]$DefaultGistUrl = 'https://gist.githubusercontent.com/fd25-cyber/06084693e9c14ed6accc0c8e165c2fbf/raw/domains.txt'
)
$ErrorActionPreference = 'Stop'

if ($RefreshDomains -and -not $DomainsUrl) {
  $DomainsUrl = $DefaultGistUrl
}

function Test-Admin {
  $id = [Security.Principal.WindowsIdentity]::GetCurrent()
  (New-Object Security.Principal.WindowsPrincipal $id).IsInRole(
    [Security.Principal.WindowsBuiltInRole]::Administrator)
}
if (-not (Test-Admin)) {
  $tmp = Join-Path $env:TEMP 'acrylic-dns-unlock-update-ip.ps1'
  if ($PSCommandPath) { Copy-Item $PSCommandPath $tmp -Force }
  else { Invoke-WebRequest -UseBasicParsing "$RepoBase/update-ip.ps1" -OutFile $tmp }
  $a = @('-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', $tmp,
         '-InstallDir', $InstallDir, '-RepoBase', $RepoBase)
  if ($NewIP) { $a += @('-NewIP', $NewIP) }
  if ($DomainsUrl) { $a += @('-DomainsUrl', $DomainsUrl) }
  if ($RefreshDomains) { $a += '-RefreshDomains' }
  Start-Process powershell -Verb RunAs -ArgumentList $a
  Write-Host 'Requesting elevation (UAC)...'
  return
}

$hostsPath = Join-Path $InstallDir 'AcrylicHosts.txt'
if (-not (Test-Path $hostsPath)) { throw "AcrylicHosts.txt not found in $InstallDir. Run install.ps1 first." }
if (-not $NewIP -and -not $DomainsUrl) { throw 'Pass -NewIP <ip>, -DomainsUrl <url>, or -RefreshDomains.' }

function Write-Utf8NoBom([string]$Path, [string]$Text) {
  [IO.File]::WriteAllText($Path, $Text, (New-Object Text.UTF8Encoding $false))
}

if ($DomainsUrl) {
  Write-Host "Fetching domains from $DomainsUrl ..."
  $tmpDom = Join-Path $env:TEMP 'acrylic-domains.txt'
  Invoke-WebRequest -UseBasicParsing $DomainsUrl -OutFile $tmpDom
  Copy-Item $tmpDom (Join-Path $InstallDir 'domains.txt') -Force
  $rules = foreach ($line in Get-Content $tmpDom) {
    if ($line -match '^\|\|(.+?)\^\$dnsrewrite=([0-9.]+)\s*$') {
      $ip = if ($NewIP) { $NewIP } else { $Matches[2] }
      "$ip >$($Matches[1])"
    }
  }
  if (-not $rules) { throw "No dnsrewrite rules parsed from $DomainsUrl" }
  $header = @(
    '# AcrylicHosts.txt - regenerated by update-ip.ps1.',
    '127.0.0.1 localhost localhost.localdomain',
    '::1 localhost localhost.localdomain',
    ''
  )
  $newContent = ($header + $rules) -join "`r`n"
  $oldContent = if (Test-Path $hostsPath) { Get-Content $hostsPath -Raw } else { '' }
  if ($newContent.Trim() -eq $oldContent.Trim()) {
    Write-Host "Domains are already up-to-date ($($rules.Count) rules). No restart needed." -ForegroundColor Green
    return
  }
  Write-Utf8NoBom $hostsPath $newContent
  Write-Host "Regenerated $($rules.Count) rules."
} else {
  $lines = Get-Content $hostsPath
  $out = foreach ($ln in $lines) {
    if ($ln -match '^\d{1,3}(\.\d{1,3}){3}\s+>') { $ln -replace '^\d{1,3}(\.\d{1,3}){3}', $NewIP }
    else { $ln }
  }
  Write-Utf8NoBom $hostsPath ($out -join "`r`n")
  Write-Host "Exit IP swapped to $NewIP."
}

Restart-Service AcrylicDNSProxySvc
ipconfig /flushdns | Out-Null
Start-Sleep -Seconds 1
Write-Host 'Service restarted, DNS cache flushed.' -ForegroundColor Green
Get-Content $hostsPath | Select-String '>' | Select-Object -First 3